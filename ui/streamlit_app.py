"""Streamlit UI. Run: streamlit run ui/streamlit_app.py
If API_URL is set it calls the REST API, otherwise it runs the pipeline in-process."""
import dataclasses
import os
import sys
from pathlib import Path

import streamlit as st

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app.config import ROOT, Settings  # noqa: E402
from app.ingestion.parser import ParseError, parse_document  # noqa: E402

st.set_page_config(page_title="Resume Intelligence", page_icon="📄", layout="wide")


@st.cache_resource(show_spinner="Loading models (first run only)...")
def _pipeline():
    from app.pipeline import build_pipeline
    return build_pipeline(Settings())


def analyze(resume_text: str, jd: str, role: str) -> dict:
    api = os.getenv("API_URL", "").rstrip("/")
    if api:
        import requests
        r = requests.post(f"{api}/analyze/text", timeout=120,
                          json={"resume_text": resume_text, "job_description": jd, "target_role": role})
        r.raise_for_status()
        return r.json()
    return dataclasses.asdict(_pipeline().analyze(resume_text, jd, role))


st.title("📄 AI Resume Intelligence & Job Matching")
st.caption("Evidence-backed skill matching: every verdict links to a resume passage.")

left, right = st.columns(2)
with left:
    st.subheader("Resume")
    up = st.file_uploader("Upload PDF / DOCX / TXT", type=["pdf", "docx", "txt"])
    use_sample = st.checkbox("Use sample resume and job description")
with right:
    st.subheader("Job description")
    role = st.text_input("Target role", value="Junior Data Scientist" if use_sample else "")
    jd_default = (ROOT / "data/samples/jd_data_scientist.txt").read_text() if use_sample else ""
    jd = st.text_area("Paste the job description", value=jd_default, height=260)

if st.button("Analyze", type="primary"):
    try:
        if use_sample:
            resume_text = (ROOT / "data/samples/resume_sample.txt").read_text()
        elif up:
            resume_text = parse_document(up.name, up.getvalue())
        else:
            st.warning("Upload a resume or tick the sample option.")
            st.stop()
        if len(jd.strip()) < 30:
            st.warning("Paste a job description first.")
            st.stop()
        with st.spinner("Retrieving evidence and analysing..."):
            res = analyze(resume_text, jd, role)
    except ParseError as e:
        st.error(str(e))
        st.stop()
    except Exception as e:
        st.error(f"Analysis failed: {e}")
        st.stop()

    if res["total_skills"] == 0:
        st.error("No recognisable skills found in the job description.")
        st.stop()

    c1, c2, c3 = st.columns(3)
    c1.metric("Match score", f"{res['coverage_score']}%")
    c2.metric("Skill coverage", f"{res['demonstrated_count']} / {res['total_skills']}")
    c3.metric("Faithfulness checks", f"{res['faithfulness']['passed']} / {res['faithfulness']['checks']}")
    st.info(res["summary"])
    if not res["llm_used"]:
        note = f" ({res['llm_error']})" if res.get("llm_error") else ""
        st.caption(f"Summary generated by the deterministic fallback, not Gemini{note}.")

    groups = {"demonstrated": "✅ Demonstrated", "partial": "🟡 Needs further evidence", "missing": "❌ Missing"}
    cols = st.columns(3)
    for col, (status, title) in zip(cols, groups.items()):
        with col:
            st.subheader(title)
            for f in [x for x in res["findings"] if x["status"] == status]:
                tag = "required" if f["importance"] == "required" else "preferred"
                with st.expander(f"{f['skill']} · {tag} · conf {f['confidence']:.2f}"):
                    st.caption(f["reason"])
                    for e in f["evidence"]:
                        st.markdown(f"> {e['text']}")
                        st.caption(f"`{e['chunk_id']}` · {e['section']} · {e['match_type']}"
                                   + (f" · {e['context']}" if e["context"] else ""))

    st.subheader("What to improve before applying")
    for s in res["suggestions"]:
        st.markdown(f"**{s['skill']}** — {s['advice']}")
    if res["faithfulness"]["issues"]:
        with st.expander("Faithfulness issues"):
            st.write(res["faithfulness"]["issues"])
